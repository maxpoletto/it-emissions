import {build} from 'esbuild';
import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {parseArgs} from 'node:util';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
export async function buildApp({check = false, deploymentEnvironment = 'uzh', output} = {}) {
    if (!['uzh', 'maxp'].includes(deploymentEnvironment))
        throw new Error('Unknown deployment environment: ' + deploymentEnvironment + '. Choose uzh or maxp.');
    const bundle = await build({entryPoints: [path.join(root, 'src/browser.js')], bundle: true,
        write: false, minify: true, format: 'iife', target: 'es2022', legalComments: 'inline'});
    const template = await readFile(path.join(root, 'app/calculator.template.html'), 'utf8');
    const cssPath = path.join(root, 'app/assets/css/main.css');
    let css = await readFile(cssPath, 'utf8');
    const fonts = [...new Set([...css.matchAll(/url\("(\.\.\/fonts\/[^"\)]+)"\)/g)].map(m => m[1]))];
    for (const font of fonts) {
        const bytes = await readFile(path.resolve(path.dirname(cssPath), font));
        const mime = font.endsWith('woff2') ? 'font/woff2' : 'font/woff';
        css = css.replaceAll(`url("${font}")`, `url("data:${mime};base64,${bytes.toString('base64')}")`);
    }
    const deploymentCss = await readFile(path.join(root, `app/deployments/${deploymentEnvironment}.css`), 'utf8');
    let header = '';
    if (deploymentEnvironment === 'maxp') {
        const logo = await readFile(path.join(root, 'app/assets/uzh_logo.svg'));
        header = (await readFile(path.join(root, 'app/deployments/maxp-header.html'), 'utf8'))
            .replace('{{UZH_LOGO_URL}}', 'data:image/svg+xml;base64,' + logo.toString('base64'));
    }
    // Escape the HTML parser's script terminator without altering JavaScript strings.
    const js = bundle.outputFiles[0].text.replaceAll('</script', '<\\/script');
    const html = `<!-- Generated by npm run build -- --deployment-environment ${deploymentEnvironment}. Edit src/, app/calculator.template.html and app/deployments/. -->\n`
        + template.replace('<!-- BASE_STYLE -->', `<style>${css}</style>`)
            .replace('<!-- DEPLOYMENT_STYLE -->', `<style>${deploymentCss}</style>`)
            .replace('            <!-- DEPLOYMENT_HEADER -->', header.trimEnd())
            .replace('{{DEPLOYMENT_ENVIRONMENT}}', deploymentEnvironment)
            .replace('<!-- APP_SCRIPT -->', `<script>${js}</script>`);
    const target = output ? path.resolve(output) : path.join(root, deploymentEnvironment === 'uzh'
        ? 'app/emissions-calculator.html' : 'output/maxp/emissions-calculator.html');
    if (check) {
        if (html !== await readFile(target, 'utf8'))
            throw new Error(`Calculator for ${deploymentEnvironment} is stale; rebuild ${target}`);
    } else {
        await mkdir(path.dirname(target), {recursive: true});
        await writeFile(target, html);
    }
    return {deploymentEnvironment, output: target};
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
    const {values} = parseArgs({options: {
        'deployment-environment': {type: 'string', default: 'uzh'},
        output: {type: 'string'}, check: {type: 'boolean'}, help: {type: 'boolean'},
    }});
    if (values.help) console.log('Usage: npm run build -- [--deployment-environment uzh|maxp] [--output file.html] [--check]');
    else {
        const result = await buildApp({deploymentEnvironment: values['deployment-environment'], output: values.output, check: values.check});
        console.log(`${values.check ? 'Checked' : 'Built'} ${result.deploymentEnvironment}: ${result.output}`);
    }
}
