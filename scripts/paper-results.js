import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import {parseArgs} from 'node:util';
import {report, calculate, merge, MODEL_VERSION} from '../src/model.js';
import {rowTotal} from '../src/components.js';
import {loadScenario, interventionComparison} from './scenarios.js';

const root = fileURLToPath(new URL('../', import.meta.url));
const percent = (part, total) => part / total * 100;

export async function paperResults() {
    const names = ['baseline', 'cloud', 'sens1', 'sens-combined', 'lifecycle-before', 'lifecycle-after'];
    const scenarios = {}, sources = [];
    for (const name of names) {
        const scenario = await loadScenario(name);
        scenarios[name] = {description: scenario.description, ...report(scenario.configuration)};
        sources.push(...scenario.sources);
    }
    const base = scenarios.baseline, cloud = scenarios.cloud;
    const total = base.results.summary.totalCombined;
    const row = (scenario, category) => scenario.results.data.find(r => r.category === category);
    const endUsers = base.results.data.filter(r => ['Laptops', 'Monitors', 'Desktops', 'Mobile phones', 'A/V equipment', 'Printers'].includes(r.category));
    const cscs = row(base, 'Supercomputing'), network = row(base, 'Campus networking');
    const agentCase = (agentUsers, kwhPerAgentDay) => rowTotal(calculate(merge(base.parameters, {
        environments: {ai: {agentUsers, kwhPerAgentDay}}})).rows.find(r => r.category === 'AI (agents)'));
    const before = scenarios['lifecycle-before'], after = scenarios['lifecycle-after'];
    const lifetime = interventionComparison(before.parameters, (await loadScenario('lifecycle-after')).overrides);
    const combined = scenarios['sens-combined'];
    const metrics = {
        BaselineKt: total / 1e6, CloudKt: cloud.results.summary.totalCombined / 1e6,
        CloudSavingT: (total - cloud.results.summary.totalCombined) / 1000,
        LaptopEmbodiedPercent: percent(row(base, 'Laptops').embodied, rowTotal(row(base, 'Laptops'))),
        EndUserEmbodiedPercent: percent(endUsers.reduce((n, r) => n + r.embodied, 0), total),
        EndUserOperationalPercent: percent(endUsers.reduce((n, r) => n + r.usage, 0), endUsers.reduce((n, r) => n + rowTotal(r), 0)),
        CscsHardwareT: cscs.embodied / 1000, CscsTotalT: rowTotal(cscs) / 1000,
        CscsLowT: cscs.range.low / 1000, CscsHighT: cscs.range.high / 1000,
        NetworkTotalT: rowTotal(network) / 1000,
        ChatT: rowTotal(row(base, 'AI (chatbot)')) / 1000,
        ChatPercent: percent(rowTotal(row(base, 'AI (chatbot)')), total),
        ChatFinalT: base.results.projection.at(-1).total / 1000,
        AgentDefaultT: rowTotal(row(base, 'AI (agents)')) / 1000,
        AgentFivePercentT: agentCase(1900, 1.3) / 1000, AgentHighT: agentCase(3800, 2.4) / 1000,
        AgentCoefficient: agentCase(38000, 1) / 1000,
        SensOneChatPercent: percent(rowTotal(row(scenarios.sens1, 'AI (chatbot)')), scenarios.sens1.results.summary.totalCombined),
        CombinedChatPercent: percent(rowTotal(row(combined, 'AI (chatbot)')), combined.results.summary.totalCombined),
        CombinedWithoutAgentsPercent: percent(rowTotal(row(combined, 'AI (chatbot)')),
            combined.results.summary.totalCombined - rowTotal(row(combined, 'AI (agents)'))),
        LifetimeBeforeKt: before.results.summary.totalCombined / 1e6,
        LifetimeAfterKt: after.results.summary.totalCombined / 1e6,
        LifetimeSavingT: lifetime.savings.central / 1000,
        LifetimeSavingPercent: percent(lifetime.savings.central, lifetime.baselineTotal),
    };
    return {metadata: {modelVersion: MODEL_VERSION, referenceYear: base.parameters.referenceYear,
        description: 'Numerical claims derived from saved scenarios; no historical validation claim is generated'},
    sources: [...new Map(sources.map(source => [source.path, source])).values()], metrics, lifetimeComparison: lifetime, scenarios};
}

export async function generatePaperResults(outputDirectory = path.join(root, 'doc'), {check = false} = {}) {
    const record = await paperResults();
    const tex = '% Generated by scripts/paper-results.js from the shared calculator. Do not edit.\n'
        + Object.entries(record.metrics).map(([name, value]) => {
            const decimals = name.endsWith('Kt') ? 2 : name === 'AgentCoefficient' ? 0 : 1;
            return `\\newcommand{\\Model${name}}{${value.toFixed(decimals)}}`;
        }).join('\n') + '\n';
    const files = [['model-results.tex', tex], ['figure-data/paper-results.json', JSON.stringify(record, null, 2) + '\n']];
    for (const [filename, text] of files) {
        const target = path.join(outputDirectory, filename);
        if (check) {
            if (await readFile(target, 'utf8') !== text) throw new Error('Stale paper results: ' + filename);
        } else {
            await mkdir(path.dirname(target), {recursive: true}); await writeFile(target, text);
        }
    }
    return record;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    const {values} = parseArgs({options: {check: {type: 'boolean'}, output: {type: 'string'}}});
    await generatePaperResults(values.output, {check: values.check});
}
